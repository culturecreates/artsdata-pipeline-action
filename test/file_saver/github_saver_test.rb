# Stand-in for Octokit::Client: records calls and returns canned responses.
class FakeOctokitClient
  Resource = Struct.new(:sha, :default_branch, keyword_init: true)

  attr_reader :calls

  def initialize(existing_file: true, write_response:, last_commit_sha: nil, commits_error: nil)
    @existing_file = existing_file
    @write_response = write_response
    @last_commit_sha = last_commit_sha
    @commits_error = commits_error
    @calls = []
  end

  def contents(_repo, path:)
    raise Octokit::NotFound unless @existing_file
    Resource.new(sha: 'blob-sha')
  end

  def update_contents(*)
    @calls << :update_contents
    @write_response
  end

  def create_contents(*)
    @calls << :create_contents
    @write_response
  end

  def repository(_repo)
    Resource.new(default_branch: 'master')
  end

  def commits(_repo, branch, path:, per_page:)
    @calls << [:commits, branch, path, per_page]
    raise @commits_error if @commits_error
    @last_commit_sha ? [Resource.new(sha: @last_commit_sha)] : []
  end
end

class GitHubSaverServiceTest < Minitest::Test
  REPO = 'culturecreates/artsdata-data'
  PATH = 'output/test-artifact.jsonld'

  def build_saver(client)
    saver = FileSaverService::GitHubSaverService.new(
      repository: REPO,
      path: PATH,
      message: 'Add data generated by the script',
      access_token: 'dummy-token',
      author_name: 'GitHub Actions',
      author_email: 'actions@github.com'
    )
    saver.instance_variable_set(:@client, client)
    saver
  end

  def test_update_returns_url_pinned_to_write_commit
    client = FakeOctokitClient.new(
      write_response: { content: { sha: 'blob-sha-new' }, commit: { sha: 'abc123' } }
    )

    url = build_saver(client).save('{}')

    assert_equal "https://raw.githubusercontent.com/#{REPO}/abc123/#{PATH}", url
    assert_equal [:update_contents], client.calls
  end

  def test_create_returns_url_pinned_to_write_commit
    client = FakeOctokitClient.new(
      existing_file: false,
      write_response: { content: { sha: 'blob-sha-new' }, commit: { sha: 'def456' } }
    )

    url = build_saver(client).save('{}')

    assert_equal "https://raw.githubusercontent.com/#{REPO}/def456/#{PATH}", url
    assert_equal [:create_contents], client.calls
  end

  def test_url_contains_no_token
    client = FakeOctokitClient.new(write_response: { commit: { sha: 'abc123' } })

    url = build_saver(client).save('{}')

    refute_includes url, 'dummy-token'
    refute_includes url, 'token='
  end

  def test_falls_back_to_last_commit_on_default_branch
    client = FakeOctokitClient.new(
      write_response: { content: { sha: 'blob-sha-new' } },
      last_commit_sha: 'fff999'
    )

    url = build_saver(client).save('{}')

    assert_equal "https://raw.githubusercontent.com/#{REPO}/fff999/#{PATH}", url
    assert_includes client.calls, [:commits, 'master', PATH, 1]
  end

  def test_returns_nil_when_no_commit_can_be_resolved
    client = FakeOctokitClient.new(write_response: { content: { sha: 'blob-sha-new' } })

    assert_nil build_saver(client).save('{}')
  end

  def test_returns_nil_when_fallback_lookup_fails
    client = FakeOctokitClient.new(
      write_response: { content: { sha: 'blob-sha-new' } },
      commits_error: Octokit::Error.new
    )

    assert_output(/could not resolve commit/) do
      assert_nil build_saver(client).save('{}')
    end
  end
end
